@pytest.mark.parametrize("src,want", CASES)
def test_cases(src, want):
    assert to_speech(src) == want


def test_ambiguous_beon_is_noted():
    r = analyze("정답은 3번에 있습니다.")
    assert r.speech == "정답은 3번에 있습니다."
    assert r.notes and r.notes[0][0].startswith("바꾸지 않음(번)")


def test_ambiguous_date_is_noted():
    r = analyze("1/12 접수")
    assert r.speech == "일 월 십이 일 접수"
    assert r.notes and r.notes[0][0].startswith("날짜로 읽음")


