def _job_scenes():
    jobs = Path(__file__).resolve().parents[2] / "jobs"
    for p in sorted(jobs.glob("*/scenes.json")):
        for s in json.loads(p.read_text(encoding="utf-8"))["scenes"]:
            yield p.parent.name, s["id"], s["narration"]


def test_punctuation_preserved_in_local_jobs():
    """로컬 jobs/ 대본 전체 검사. jobs/는 git 제외 폴더라 없으면 건너뛴다 (내용은 저장소에 넣지 않음)"""
    scenes = list(_job_scenes())
    if not scenes:
        pytest.skip("jobs/*/scenes.json 없음")
    bad = [(job, sid) for job, sid, text in scenes if _punct_counts(to_speech(text)) != _punct_counts(text)]
    assert not bad, f"문장부호 개수가 바뀐 장면: {bad}"
